CREATE TABLE hotel_role (
    role_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name VARCHAR(64) NOT NULL UNIQUE
);

CREATE TABLE hotel_permission (
    permission_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    permission_name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE hotel_role_permissions (
    role_id BIGINT NOT NULL REFERENCES hotel_role (role_id),
    permission_id BIGINT NOT NULL REFERENCES hotel_permission (permission_id),
    PRIMARY KEY (role_id, permission_id)
);

CREATE TABLE employee_user (
    user_id UUID PRIMARY KEY,
    login_name VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    failed_login_attempts INTEGER NOT NULL DEFAULT 0 CHECK (failed_login_attempts >= 0),
    locked_until TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE employee_user_roles (
    user_id UUID NOT NULL REFERENCES employee_user (user_id),
    role_id BIGINT NOT NULL REFERENCES hotel_role (role_id),
    PRIMARY KEY (user_id, role_id)
);

CREATE INDEX idx_employee_user_roles_role_id ON employee_user_roles (role_id);

