CREATE TABLE room_type (
    room_type_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(32) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(1000),
    max_occupancy SMALLINT NOT NULL CHECK (max_occupancy > 0),
    base_nightly_rate NUMERIC(12, 2) NOT NULL CHECK (base_nightly_rate > 0),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE hotel_room (
    room_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_number VARCHAR(32) NOT NULL UNIQUE,
    room_type_id BIGINT NOT NULL REFERENCES room_type (room_type_id),
    floor_label VARCHAR(32),
    operational_status VARCHAR(24) NOT NULL
        CHECK (operational_status IN ('AVAILABLE', 'OCCUPIED', 'OUT_OF_SERVICE')),
    housekeeping_status VARCHAR(24) NOT NULL
        CHECK (housekeeping_status IN ('CLEAN', 'DIRTY', 'IN_PROGRESS', 'INSPECTED')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_hotel_room_room_type_id ON hotel_room (room_type_id);
CREATE INDEX idx_hotel_room_operational_status ON hotel_room (operational_status);
CREATE INDEX idx_hotel_room_housekeeping_status ON hotel_room (housekeeping_status);
