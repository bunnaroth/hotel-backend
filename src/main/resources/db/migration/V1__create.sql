CREATE TABLE hotel_settings (
    settings_id SMALLINT PRIMARY KEY CHECK (settings_id = 1),
    hotel_name VARCHAR(160) NOT NULL,
    street_address VARCHAR(300) NOT NULL,
    phone_number VARCHAR(40),
    contact_email VARCHAR(254),
    time_zone VARCHAR(100) NOT NULL,
    currency_code VARCHAR(3) NOT NULL CHECK (currency_code ~ '^[A-Z]{3}$'),
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE room_type (
    room_type_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(32) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    category VARCHAR(16) NOT NULL CHECK (category IN ('PRIVATE', 'DORMITORY')),
    image_key VARCHAR(32) NOT NULL CHECK (image_key IN (
        'ROOM_PLACEHOLDER',
        'PVT_SD',
        'PVT_ST',
        'PVT_DLX',
        'PVT_FAM',
        'DRM_4M',
        'DRM_6M',
        'DRM_6F',
        'DRM_8M'
    )),
    description VARCHAR(1000),
    max_occupancy SMALLINT NOT NULL CHECK (max_occupancy > 0),
    room_limit INTEGER NOT NULL CHECK (room_limit > 0),
    base_nightly_rate NUMERIC(12, 2) NOT NULL CHECK (base_nightly_rate > 0),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE hotel_room (
    room_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_number VARCHAR(32) NOT NULL UNIQUE,
    room_type_id BIGINT NOT NULL REFERENCES room_type (room_type_id),
    operational_status VARCHAR(24) NOT NULL
        CHECK (operational_status IN ('AVAILABLE', 'OCCUPIED', 'OUT_OF_SERVICE')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_hotel_room_room_type_id ON hotel_room (room_type_id);
CREATE INDEX idx_hotel_room_operational_status ON hotel_room (operational_status);

CREATE TABLE guest (
    guest_id UUID PRIMARY KEY,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    email VARCHAR(254),
    phone_number VARCHAR(40),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (email IS NOT NULL OR phone_number IS NOT NULL)
);

CREATE INDEX idx_guest_email ON guest (email);

CREATE TABLE reservation (
    reservation_id UUID PRIMARY KEY,
    booking_reference VARCHAR(24) NOT NULL UNIQUE,
    primary_guest_id UUID NOT NULL REFERENCES guest (guest_id),
    check_in_date DATE NOT NULL,
    check_out_date DATE NOT NULL,
    status VARCHAR(24) NOT NULL
        CHECK (status IN ('PENDING', 'CONFIRMED', 'CHECKED_IN', 'CHECKED_OUT', 'CANCELLED', 'NO_SHOW')),
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    CHECK (check_in_date < check_out_date)
);

CREATE INDEX idx_reservation_primary_guest_id ON reservation (primary_guest_id);
CREATE INDEX idx_reservation_status_expires_at ON reservation (status, expires_at);

CREATE TABLE reservation_guest (
    reservation_id UUID NOT NULL REFERENCES reservation (reservation_id),
    guest_id UUID NOT NULL REFERENCES guest (guest_id),
    PRIMARY KEY (reservation_id, guest_id)
);

CREATE INDEX idx_reservation_guest_guest_id ON reservation_guest (guest_id);

CREATE TABLE room_allocation (
    allocation_id UUID PRIMARY KEY,
    reservation_id UUID NOT NULL REFERENCES reservation (reservation_id),
    room_id BIGINT NOT NULL REFERENCES hotel_room (room_id),
    check_in_date DATE NOT NULL,
    check_out_date DATE NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (check_in_date < check_out_date)
);

CREATE INDEX idx_room_allocation_reservation_id ON room_allocation (reservation_id);
CREATE INDEX idx_room_allocation_room_dates_active
    ON room_allocation (room_id, check_in_date, check_out_date, active);

CREATE TABLE reservation_payment (
    payment_id UUID PRIMARY KEY,
    reservation_id UUID NOT NULL REFERENCES reservation (reservation_id),
    provider VARCHAR(32) NOT NULL,
    provider_reference VARCHAR(128),
    status VARCHAR(16) NOT NULL
        CHECK (status IN ('PENDING', 'AUTHORIZED', 'CAPTURED', 'REFUNDED', 'FAILED')),
    amount NUMERIC(12, 2) NOT NULL,
    currency VARCHAR(3) NOT NULL,
    checkout_session_id VARCHAR(255) UNIQUE,
    checkout_url VARCHAR(2048),
    checkout_expires_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_reservation_payment_reservation_id ON reservation_payment (reservation_id);
CREATE INDEX idx_reservation_payment_status ON reservation_payment (status);

CREATE TABLE reservation_lookup_challenge (
    challenge_id UUID PRIMARY KEY,
    reservation_id UUID REFERENCES reservation (reservation_id) ON DELETE SET NULL,
    lookup_hash VARCHAR(64) NOT NULL,
    client_ip_hash VARCHAR(64) NOT NULL,
    code_hash VARCHAR(64) NOT NULL,
    attempt_count INTEGER NOT NULL DEFAULT 0 CHECK (attempt_count BETWEEN 0 AND 5),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    consumed_at TIMESTAMP WITH TIME ZONE
);

CREATE INDEX idx_res_lookup_lookup_created
    ON reservation_lookup_challenge (lookup_hash, created_at);
CREATE INDEX idx_res_lookup_ip_created
    ON reservation_lookup_challenge (client_ip_hash, created_at);
CREATE INDEX idx_res_lookup_expires_at
    ON reservation_lookup_challenge (expires_at);
